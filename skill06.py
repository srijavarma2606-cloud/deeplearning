preferred = [
    path for path in json_files
    if "instances" in os.path.basename(path).lower()
]

annotation_path = preferred[0] if preferred else json_files[0]

with open(annotation_path, "r") as f:
    coco = json.load(f)

images = coco.get("images", [])
annotations = coco.get("annotations", [])
categories = coco.get("categories", [])

if not images or not categories:
    raise ValueError("Invalid COCO dataset structure.")

category_map = {
    category["id"]: category["name"]
    for category in categories
}

image_map = {
    image["id"]: image
    for image in images
}

print("\nDataset loaded successfully!")
print("Total images:", len(images))
print("Total annotations:", len(annotations))
print("Total categories:", len(categories))

# ------------------------------------------------------------
# STEP 3: FIND IMAGE FILES
# ------------------------------------------------------------

image_extensions = (".jpg", ".jpeg", ".png", ".bmp", ".webp")

image_paths = {}

for root, dirs, filenames in os.walk(extract_path):
    for filename in filenames:

        if filename.lower().endswith(image_extensions):

            full_path = os.path.join(root, filename)

            relative_path = os.path.relpath(
                full_path, extract_path
            ).replace("\\", "/")

            image_paths[relative_path] = full_path


def find_image(file_name):

    normalized = str(file_name).replace("\\", "/").lstrip("./")

    if normalized in image_paths:
        return image_paths[normalized]

    basename = os.path.basename(normalized)

    matches = [
        path for path in image_paths.values()
        if os.path.basename(path) == basename
    ]

    return matches[0] if matches else None


