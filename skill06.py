# STEP 7: ANNOTATION VISUALISATION
# ------------------------------------------------------------

print("\n" + "=" * 65)
print("STEP 4: ANNOTATION VISUALISATION")
print("=" * 65)

annotations_by_image = {}

for annotation in annotations:

    image_id = annotation.get("image_id")

    annotations_by_image.setdefault(
        image_id, []
    ).append(annotation)


sample_images = []

for image_info in images:

    image_id = image_info["id"]

    if image_id in annotations_by_image:

        path = find_image(
            image_info.get("file_name", "")
        )

        if path and os.path.exists(path):
            sample_images.append(image_info)


if not sample_images:

    print("No annotated images available.")

else:

    random.seed(42)

    selected_images = random.sample(
        sample_images,
        min(5, len(sample_images))
    )

    fig, axes = plt.subplots(
        len(selected_images),
        1,
        figsize=(14, 6 * len(selected_images))
    )

    if len(selected_images) == 1:
        axes = [axes]

    for ax, image_info in zip(axes, selected_images):

        image_id = image_info["id"]

        image_path = find_image(
            image_info.get("file_name", "")
        )

        img = cv2.imread(image_path)

        img = cv2.cvtColor(
            img, cv2.COLOR_BGR2RGB
        )

        for annotation in annotations_by_image.get(image_id, []):

            bbox = annotation.get("bbox")

            if not isinstance(bbox, (list, tuple)) or len(bbox) != 4:
                continue

            try:

                x, y, w, h = map(float, bbox)

                if not np.all(np.isfinite([x, y, w, h])):
                    continue

                if w <= 0 or h <= 0:
                    continue

                category_id = annotation.get("category_id")

                label = category_map.get(
                    category_id, "Unknown"
                )

                x1 = int(max(0, x))
                y1 = int(max(0, y))

                x2 = int(min(img.shape[1], x + w))
                y2 = int(min(img.shape[0], y + h))

                if x2 <= x1 or y2 <= y1:
                    continue

                cv2.rectangle(
                    img,
                    (x1, y1),
                    (x2, y2),
                    (0, 255, 0),
                    3
                )

                cv2.putText(
                    img,
                    label,
                    (x1, max(20, y1 - 5)),
                    cv2.FONT_HERSHEY_SIMPLEX,
                    0.7,
                    (255, 0, 0),
                    2
                )

            except (ValueError, TypeError):
                continue

        ax.imshow(img)

        ax.set_title(
            f"Image ID: {image_id} - "
            f"{image_info.get('file_name', '')}"
        )

        ax.axis("off")

    plt.tight_layout()
    plt.show()


