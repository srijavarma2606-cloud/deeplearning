# ------------------------------------------------------------
# STEP 5: IMAGE QUALITY AUDIT
# ------------------------------------------------------------

print("\n" + "=" * 65)
print("STEP 2: IMAGE QUALITY AUDIT")
print("=" * 65)

quality_results = []
hashes = {}

for index, image_info in enumerate(images):

    file_name = image_info.get("file_name", "")
    image_id = image_info.get("id")

    image_path = find_image(file_name)

    if image_path is None:

        quality_results.append({
            "Image_ID": image_id,
            "File_Name": file_name,
            "Status": "Missing",
            "Width": None,
            "Height": None,
            "Brightness": None,
            "Blur_Score": None,
            "Duplicate": None
        })

        continue

    img = cv2.imread(image_path)

    if img is None:

        quality_results.append({
            "Image_ID": image_id,
            "File_Name": file_name,
            "Status": "Corrupted",
            "Width": None,
            "Height": None,
            "Brightness": None,
            "Blur_Score": None,
            "Duplicate": None
        })

        continue

    height, width = img.shape[:2]

    gray = cv2.cvtColor(
        img, cv2.COLOR_BGR2GRAY
    )

    brightness = float(np.mean(gray))

    blur_score = float(
        cv2.Laplacian(gray, cv2.CV_64F).var()
    )

    with open(image_path, "rb") as f:
        image_hash = hashlib.md5(f.read()).hexdigest()

    duplicate = image_hash in hashes
    hashes[image_hash] = True

    issues = []

    if width < 300 or height < 200:
        issues.append("Low resolution")

    if brightness < 40:
        issues.append("Too dark")

    elif brightness > 220:
        issues.append("Too bright")

    if blur_score < 100:
        issues.append("Possibly blurry")

    if duplicate:
        issues.append("Duplicate")

    status = ", ".join(issues) if issues else "Good"

    quality_results.append({
        "Image_ID": image_id,
        "File_Name": file_name,
        "Status": status,
        "Width": width,
        "Height": height,
        "Brightness": round(brightness, 2),
        "Blur_Score": round(blur_score, 2),
        "Duplicate": duplicate
    })

    if (index + 1) % 100 == 0:
        print(f"Checked {index + 1}/{len(images)} images")


quality_df = pd.DataFrame(quality_results)

print("\nImage Quality Results:")
display(quality_df)

