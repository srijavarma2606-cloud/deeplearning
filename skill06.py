# STEP 6: ANNOTATION VALIDATION
# ------------------------------------------------------------

print("\n" + "=" * 65)
print("STEP 3: ANNOTATION VALIDATION")
print("=" * 65)

annotation_issues = []
valid_annotation_count = 0

for annotation in annotations:

    annotation_id = annotation.get("id")
    image_id = annotation.get("image_id")
    category_id = annotation.get("category_id")
    bbox = annotation.get("bbox")

    issues = []

    if image_id not in image_map:
        issues.append("Unknown image ID")

    if category_id not in category_map:
        issues.append("Unknown category ID")

    if not isinstance(bbox, (list, tuple)) or len(bbox) != 4:

        issues.append("Invalid bounding box format")

    else:

        try:

            x, y, w, h = map(float, bbox)

            if not np.all(np.isfinite([x, y, w, h])):
                issues.append("Non-finite values")

            elif w <= 0 or h <= 0:
                issues.append("Invalid width or height")

            elif x < 0 or y < 0:
                issues.append("Negative coordinates")

            elif image_id in image_map:

                img_width = image_map[image_id].get("width")
                img_height = image_map[image_id].get("height")

                if img_width is not None and img_height is not None:

                    if x + w > img_width or y + h > img_height:
                        issues.append("Bounding box outside image")

        except (ValueError, TypeError):
            issues.append("Non-numeric coordinates")

    if issues:

        annotation_issues.append({
            "Annotation_ID": annotation_id,
            "Image_ID": image_id,
            "Category_ID": category_id,
            "Issues": "; ".join(issues)
        })

    else:
        valid_annotation_count += 1


annotation_issues_df = pd.DataFrame(annotation_issues)

print("Total annotations:", len(annotations))
print("Valid annotations:", valid_annotation_count)
print("Invalid annotations:", len(annotation_issues_df))

if not annotation_issues_df.empty:
    display(annotation_issues_df)
else:
    print("No annotation errors detected!")


