image_extensions = (".jpg", ".jpeg", ".png", ".bmp")

image_map = {}

for root, dirs, filenames in os.walk(extract_path):

    for filename in filenames:

        if filename.lower().endswith(image_extensions):

            image_map[filename] = os.path.join(
                root, filename
            )

print("Total images found:", len(image_map))

def visualize_image(image_id):

    image_info = next(
        img for img in coco_data["images"]
        if img["id"] == image_id
    )

    filename = os.path.basename(image_info["file_name"])

    image_path = image_map.get(filename)

    if image_path is None:
        print("Image not found:", filename)
        return

    image = cv2.imread(image_path)

    if image is None:
        print("Unable to read image!")
        return

    image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

    annotations = [
        ann for ann in coco_data["annotations"]
        if ann["image_id"] == image_id
    ]

    for ann in annotations:

        x, y, w, h = map(int, ann["bbox"])

        label = category_names[ann["category_id"]]

        cv2.rectangle(
            image,
            (x, y),
            (x + w, y + h),
            (0, 255, 0),
            2
        )

        cv2.putText(
            image,
            label,
            (x, max(y - 5, 15)),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (255, 0, 0),
            2
        )

    plt.figure(figsize=(12, 7))
    plt.imshow(image)
    plt.title("Traffic Image with Bounding Boxes")
    plt.axis("off")
    plt.show()

    print("Image:", filename)
    print("Total Objects:", len(annotations))

